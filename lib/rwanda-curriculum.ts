/** Get subjects for a given grade */
export function getSubjectsForGrade(grade: GradeLevel): string[] {
  return RWANDAN_CURRICULUM[grade].subjects.map((s) => s.name)
}

/** Get topics for a given grade and subject */
export function getTopicsForGradeAndSubject(
  grade: GradeLevel,
  subjectName: string
): string[] {
  const curriculum = RWANDAN_CURRICULUM[grade]
  const subject = curriculum.subjects.find((s) => s.name === subjectName)
  return subject?.topics ?? []
}

/** Get curriculum context string for AI prompt */
export function getCurriculumContext(
  grade: GradeLevel,
  subjectName: string,
  selectedTopics: string[]
): string {
  const gradeInfo = RWANDAN_CURRICULUM[grade]
  return `**Curriculum Authority:** Rwanda Education Board (REB) – Competence-Based Curriculum
**Grade Level:** Grade ${grade} (${gradeInfo.rwandaLevel} – ${gradeInfo.description})
**Subject:** ${subjectName}
**Topics from REB Syllabus:** ${selectedTopics.join(', ')}

The questions MUST strictly align with the Rwanda National Competence-Based Curriculum as prescribed by the Rwanda Education Board (REB). Questions should:
- Reflect the cognitive demands appropriate for ${gradeInfo.rwandaLevel} students
- Use terminology and context consistent with the REB syllabus
- Be exam-ready for Rwanda's national assessment standards (${grade <= 6 ? 'Primary Leaving Examination (PLE)' : grade <= 9 ? 'O-Level for S1–S3' : 'A-Level for S4–S6'})
- Include application-based and analytical questions as per the competence-based approach`
}
